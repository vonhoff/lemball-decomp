// FUNCTION: LEMBALL 0x0045a940
VsTrig::VsTrig()
{
	if (g_dwVSTrigInitialised == 0) {
		const int* pSource = g_nVSTrigSource;
		Fixed* pTable = m_sine;
		do {
			int val = *pSource++;
			int fixedVal = val << 12;
			pTable->m_value = fixedVal / 4096;
			pTable++;
		} while (pSource < (const int*) &g_dwVSTrigInitialised);
	}
	g_dwVSTrigInitialised = 1;
}

